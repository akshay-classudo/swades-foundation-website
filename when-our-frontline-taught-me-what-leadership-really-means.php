      <span>Reflection</span>
      <h2>When Our Frontline Taught Me What Leadership Really Means</h2>
      <p></p>
    </div><!--detail-hd-->

    <div class="detail-werap">
      <div class="initiative">
        <h5>When the pandemic hit in 2020, all of us were caught off guard.</h5>

        <p>None of us knew how to navigate a crisis of this nature or intensity. It didn't matter whether you sat behind a desk or were out in the field, in a classroom, a corner office, or managing a household. It was a difficult time for everyone, but a particularly testing one for anyone in a leadership role, because people naturally look to you for direction, for answers, and for reassurance.</p>

        <p>Our team at Swades was no different. Beyond the fear for the health of loved ones, there was a very real anxiety about what this crisis meant for salaries, livelihoods, and stability. While I was trying to get a grip on the situation and find answers to the many questions around Swades' operations and direction, something happened that I will never forget.</p>

        <p>Our HODs and senior leaders offered to take pay cuts. Voluntarily. So that no one else would have to lose their job. Our founders had been very clear from the start: come what may, we were not letting anyone go, at least for the foreseeable future.</p>

        <p>The willingness of our senior team gave me the confidence to follow through on that commitment. So we went to our frontline teams with a simple promise: your jobs are safe. There will be no raises this year, but there will be no layoffs either.</p>
      </div>

      <div class="blog-post">
        <img src="./assets/images/Blogs/reflection5.png" alt="">
      </div>

      <div class="initiative2">
        <h5>Leadership rises from the ground up</h5>

        <p>And then came the moment that truly humbled me. Our frontline workers, the very people we were trying to protect, offered to take a hit to their own pockets. But it didn't stop there. They went a step further, volunteering to serve their communities in ways that had nothing to do with their official roles - distributing food packets, mobilising villages for vaccination, and doing whatever was needed on the ground.</p>

        <p>At a time when I was putting pressure on myself to lead from the front, the organisation had already stepped up and led the way. It was a powerful reminder that leadership doesn't always flow from the top down; often, it rises from the ground up.</p>

        <p>That's when the true meaning of organisational culture struck me. Culture is something we live every day, but its real strength reveals itself in moments of crisis. The solidarity we witnessed wasn't accidental - it was built over years of trust, shared purpose, and showing up for one another.</p>

        <p>When the moment came, we didn't have to ask people to care because they already did.</p>

        <p>My biggest takeaway from this experience is simple: a crisis doesn't just build character, it reveals the foundation you've been quietly building over the years. Culture isn't created in difficult moments. It is shaped every day, and needs to be lived, nurtured, and protected on easy days and difficult days.</p>

