      <span>Reflection</span>
      <h2>Community-Driven Change Needs Shared Goals; Not Set Targets</h2>
      <p></p>
    </div><!--detail-hd-->

    <div class="detail-werap">
      <div class="initiative">
        <h5>Decades in the corporate world condition you to think on the lines of targets - quarterly targets, annual targets, monthly targets etc.</h5>

        <p>Targets are like your north star - they dictate your decisions, tell you which direction to go in, how far you've come and so on. When I moved to the social sector, I brought that target-driven mindset with me, assuming that it would adapt here as well and for a while, it did seem to.</p>

        <p>I remember a period in 2016-17 and 2017-18 when we used to do budgeting. We set targets for everything. Number of toilets to be built, number of goats to be distributed to low-income households, number of cattle to be distributed to supplement farm incomes, donors' commitment to utilise the funds in time, etc.</p>

        <p>For a while the numbers looked good, but slowly, I could see some gaps that were emerging in this approach. What looked good on paper didn't always translate on the field. For example, toilets were being built, but not used fully by the community. Goats were being distributed as planned, but mortality was rising.</p>

        <p>So in 2018-19, we revisited our approach to understand what we may have overlooked and whether our initial assessment of the targets had been accurate. We had identified the need correctly, but we were not working with the right approach. Communities were treating our programmes the way you treat items out of a catalogue: pick what looks useful, sign up, and wait for delivery.</p>

        <p>The stakes felt low because the decision had never been theirs. We had identified a gap and tried to fill it in ways we thought were best. But filling a gap is not the same as solving a problem.</p>
      </div>

      <div class="blog-post">
        <img src="./assets/images/Blogs/reflection2.png" alt="">
      </div>

      <div class="initiative2">
        <h5>Community ownership creates lasting impact</h5>

        <p>The need was real and our intent was good but something very crucial was missing. We were 'community-centric' but not 'community-driven'. Although people use these terms interchangeably, they are not the same. Community-centric means the work is 'for' the community. Well-intentioned, but power sits with the organisation. Community participation goes further: consultations, feedback, local involvement etc. This is a better approach, but power still largely sits outside.</p>

        <p>Community-driven is different entirely. This is where the community comes forward to co-design and decide alongside you. They are not recipients or beneficiaries, but partners and co-owners in driving change.</p>

        <p>One of the big shifts which brings in community ownership happens through convening power tests which we started doing to gauge a community's ability to set aside social and political differences and unite for a larger cause - this could be cleaning the village, digging soak pits etc. Also glad to share that in the past three months, after entering Nandurbar, Palghar and Thane, we have seen an excellent response. As our teams began engaging with communities, villagers built 1,200 soak pits on their own without any direct intervention from Swades.</p>

        <p>We started insisting that they form a volunteer village development committee that will take ownership on behalf of the village and help identify need and demand. We started grading them as green, yellow and red on the basis of their effort. In short, we made it 'difficult' for them to work with us. And yet, the toilets got built better, goat mortality reduced considerably, and all other programmes showed better results.</p>

        <p>With this positive change which we witnessed over the last 7-8 years, more donors joined hands and are happy with the sustained impact of our work.</p>

        <p>In 2016, we had 350 employees across 6 blocks. Today we are in 17 blocks of rural Maharashtra with a little over 275 people – not because we decided to drastically cut manpower, but because we now have 12,000+ trained community volunteers who share the work. We have more than 70 donors who started believing and committing for multi-year grants.</p>

        <p>It is what happens when communities step forward to carry their share, because now they have skin in the game. They care about the fruit of their labour. It is also Swades' core philosophy at work - <strong>Swa Se Bane Des</strong> - one makes one's own country.</p>

        <p>External support can enable and accelerate change, but lasting impact is created when communities lead from the front and own the effort. Ten years down the line we do have targets to meet, but today, they are guided by community ownership.</p>

        <h5>I'd love to know your thoughts on:</h5>

        <ol>
          <li>How you understand / define community-centric, community-participatory and community-driven change?</li>
          <li>What are the challenges you faced with respect to the community's role?</li>
          <li>How do you set or measure targets / priorities in your organisation?</li>
        </ol>

