          <h3>PREVENTION OF SEXUAL HARRASMENT POLICY (POSH)</h3><br/>
          <h4>HARASSMENT FREE WORKPLACE</h4>
          <p>Swades will strive to provide a work environment, free of unlawful discrimination, harassment and/or intimidation. Such conduct interferes with an employee’s ability to perform his/her duties and is not consistent with our Company’s philosophy of trust and mutual respect.</p>
          <p>Compliance with this policy is the responsibility of all Swades employees. Every employee must avoid any behavior or conduct that could reasonably be interpreted as a violation of this policy, and every employee should try to maintain a work environment- free from discrimination, harassment or intimidation.</p>
          <p>The implementation and continued support of this policy is the responsibility of each and every Executive, Manager and Supervisor. Full cooperation and assistance is expected by all those associated with the hiring, developing, and promoting of Company employees. Employees are responsible for reporting and should submit their concern to a manager or Human Resources for further investigation. Conduct prohibited by this policy includes, but is not limited to, all unlawful discrimination, harassment and intimidation. More specifically, the prohibited conduct includes, but is not limited to:</p>
          <h4>Discrimination-Based Harassment:</h4>
          <p>Includes any verbal or physical conduct that may reasonably be perceived as demeaning or showing hostility or aversion toward an individual because of their race, color, religion, sex, pregnancy, national origin, ancestry, citizenship, age, marital status, physical or mental disability, medical condition, veteran status, sexual orientation, or other prohibited characteristics protected by state law, provincial law or country law, or because of the protected characteristics of the individual’s relatives, friends and associates.<br />This type of harassment includes, by example:</p>
          <ul class="listitem">
            <li>Epithets, slurs, negative stereotyping, or intimidating acts or statements that are based on an individual’s protected status.</li>
            <li>Written or graphic material circulated or posted within the workplace that shows hostility toward an individual because of their protected characteristics.</li>
            <li>Physical threats against, or intimidation of, an individual because of their protected characteristics.</li>
          </ul>
          <h4>Sexual Harassment (POSH):</h4>
          <ul class="listitem">
            <li>Sexual harassment includes sexual advances, request for sexual favours and/or all verbal or physical conduct when:</li>
            <li>Submission to such conduct is an explicit or implicit term or condition of employment;</li>
            <li>An individual’s submission to or rejection of such conduct becomes the basis for employment decisions affecting that individual; or</li>
          </ul>
          <p>Conduct which has the purpose or effect of interfering with an employee’s work performance or creating an intimidating, hostile or offensive working environment, such as:</p>
          <ul class="listitem">
            <li>Sexual flirtations, advances, propositions.</li>
            <li>Verbal or written comments, jokes, teasing and/or other communication of a sexual nature.</li>
            <li>Graphic comments about an individual’s body.</li>
            <li>Use of sexually degrading words to describe an individual
            <li>Display of sexually suggestive objects or pictures.</li>
            <li>Foul, obscene or sexually oriented language or gestures; and/or</li>
            <li>Physical conduct such as grabbing, patting, pinching, brushing against another person’s body, or blocking normal movement</li>
          </ul>
