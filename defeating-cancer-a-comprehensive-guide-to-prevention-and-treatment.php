          <h5>India’s challenge with cancer</h5>

          <p>India is estimated to have 4 million prevalent cancer cases in 2020 and is expected to reach 11.2 million by 2030, with a low survival rate of less then 30%. Women carry a disproportionate burden of cancer, accounting for 51% of new cases.</p>
          <p>The three most commonly occurring cancers in India are those of the breast, uterine cervix and lip/oral cavity. Together, they account for approximately 34% of all cancers in India, and constitute a public health priority. Every year, 13.9 lakhs new cancer patients are registered in India. Out of which almost 8.5 lakhs die. In India overall, 1 in 9 (both sexes) people are at a risk of developing cancer before the age of 75 years i.e. 1 in 68 for males and 1 in 29 for females, whereas, 1 in 22 rural Indian males/females are at a risk of dying from cancer before the age of 75 years.</p>
          
