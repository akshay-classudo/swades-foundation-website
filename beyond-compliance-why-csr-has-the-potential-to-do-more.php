      <span>Reflection</span>
      <h2>Beyond Compliance: Why CSR Has The Potential To Do More</h2>
      <p></p>
    </div><!--detail-hd-->

    <div class="detail-werap">
      <div class="initiative">
        <h5>A friend recently asked me, if you went back to the corporate world, what would you do differently?</h5>

        <p>For one, I would work to optimise corporate's role in the developmental landscape. India's CSR Act was a landmark moment for the country. The intention behind it deserves real appreciation, and so does the growing number of companies stepping up to meet their commitments.</p>

        <p>But a decade in, it feels like the right time to look beyond just compliance and ask ourselves whether we are truly making the most of this very good opportunity.</p>

        <h5>Many of us in the sector will find some signs familiar:</h5>

        <ul>
          <li>Approvals that stretch on for months.</li>
          <li>Funding that arrives with multiple conditions attached.</li>
          <li>Reluctance to cover the operational costs that make all the good work possible.</li>
          <li>Insistence on seeing immediate impact.</li>
        </ul>

        <p>By the time funds reach an NGO, the financial year is often already underway, yet impact is expected on paper by March. As a result, grassroots organisations end up aligning with funder timelines rather than community needs. It is common for companies to concentrate CSR spending in their manufacturing districts, often neglecting areas where the need may be more acute.</p>

        <p>I recognise that navigating internal approvals and governance is not easy, but if these resources are being committed, there is an even stronger case to optimise how they are deployed.</p>
      </div>

      <div class="blog-post">
        <img src="./assets/images/Blogs/reflection6.png" alt="">
      </div>

      <div class="initiative2">
        <h5>Building trust for lasting social impact</h5>

        <p>Trust plays a central role here. Where there is deep trust between CSR partners and NGOs, the work tends to be more adaptive, grounded, and effective. Where trust is limited, the focus often shifts to control, compliance, and reporting.</p>

        <p>Social change cannot move on a financial year cycle and lasting change requires staying long enough to understand what is actually working, and that is nearly impossible when the clock is always ticking toward a compliance deadline.</p>

        <h5>A few shifts could make a meaningful difference:</h5>

        <ul>
          <li>Multi-year partnerships for the same cause.</li>
          <li>Greater flexibility at the programme level.</li>
          <li>Open, honest conversations with NGOs to truly understand community needs.</li>
          <li>Investing in organisations, not just projects.</li>
        </ul>

        <p>Which is why I want to take a moment to express genuine gratitude for our long-term partners - organisations that chose to place their faith in us, not just once, but year after year. That kind of sustained belief changes what is possible.</p>

        <p>It means we can plan ahead, build relationships that go deep, and stay with communities through the slow but meaningful work of change. It means our team doesn't have to spend half the year wondering if funding will come through. It means we can focus on the people we are here to serve.</p>

        <p>We would love to invite CSR leaders to a dialogue where our partners will share their experience of supporting scalable, community-driven models. Do leave a comment if you'd like to be part of this conversation.</p>

