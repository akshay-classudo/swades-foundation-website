      <span>Reflection</span>
      <h2>Why We Must Move Beyond Numbers to Measure Social Change</h2>
      <p></p>
    </div><!--detail-hd-->

    <div class="detail-werap">
      <div class="initiative">
        <h5>Most organisations return to a familiar routine at the end of a financial year – performance reviews.</h5>

        <p>I value this discipline – both as a corporate and as a social sector employee because metrics are important for accountability and clarity of goal. But in the social sector, numbers, while necessary, are never sufficient. We often fall short not because change isn't happening, but because we don't yet have the right ways to measure it.</p>

        <p>Metrics like income increase or health outcomes can be captured. But the deeper transformations in mindset, behaviour, agency and confidence are different. They have to be seen and experienced. I have witnessed this firsthand during field visits.</p>

        <p>In some villages, women who once stood quietly at the back of a gathering slowly began to speak up. Over time, they became central voices in discussions and eventually members of Village Development Committees. Take Vidya Kule. After losing her husband to TB, she chose to step forward as a Swades Mitra, a trained health volunteer. She played a key role in helping her village become TB-free and later went on to become the Sarpanch. How do you capture a journey like that on a sheet?</p>

        <p>Our systems tend to prioritise what is easily quantifiable - assets created, funds deployed, livelihoods supported. These are critical indicators, and they must be accounted for to understand one's progress. But if we stop there, we risk mistaking activity for transformation. The deeper outcomes such as dignity, confidence, and resilience are harder to measure, but they are ultimately what sustain change.</p>
      </div>

      <div class="blog-post">
        <img src="./assets/images/Blogs/reflection8.png" alt="">
      </div>

      <div class="initiative2">
        <h5>Measuring What Truly Matters</h5>

        <p>This is where strategy must evolve. As leaders, we need to ask: are we measuring what is convenient, or what is critical? The answer has implications not just for reporting, but for how programmes are designed, how teams are incentivised, and how success itself is defined.</p>

        <p>In our own work, we have seen how powerful this shift in perspective can be. Take Washihaveli Koliwada.</p>

        <p>Infrastructure and funding helped drive visible improvements, but the real transformation was much deeper. As a fishing village, Washihaveli was once stigmatised for the stench of unmanaged fish waste and poor hygiene. So much so that women were reluctant to marry into the community. Today, it stands as a Swades Dream Village.</p>

        <p>On its own initiative, the village secured a 10 lakh grant under the Swacch Bharat Mission and introduced innovations like installing wash basins across households - well beyond what was originally envisioned with Swades. The community had rebuilt its sense of pride and ownership. And this is not the story of just Washihaveli. There are hundreds of such stories across Swades villages in Maharashtra.</p>

        <p>As expectations for accountability increase, the sector must broaden its definition of impact. We need measurement approaches that capture not just outputs, but outcomes and intent. Because ultimately, the most strategic investment we make is not just in programmes, it is in people.</p>

        <h5>I'd love to know from you:</h5>

        <ul>
          <li>When was the last time you witnessed a shift that could not be captured in the traditional sense?</li>
          <li>How can we build systems that capture dignity, agency and confidence alongside traditional metrics?</li>
        </ul>

