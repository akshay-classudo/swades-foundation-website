        <h2 class="story-title">How a young farmer has transformed his family’s paddy fields into thriving farms</h2>

        <p class="story-lead">Unlike many young boys and girls from his village, Amar Rajendra Kadam never aspired for city life. But when challenges on the family farm grew, he took up a job in Mumbai.</p>

        <p class="story-lead">When the Covid lockdown brought him back to Naneghol village (Poladpur taluka), Amar saw it as a sign—to return to his roots and revive the land his grandparents once cultivated with love, though it had only ever grown paddy.</p>

        <p class="story-lead image_side">Determined to make rural life work, he began planting saplings, only to watch them wither in the scorching Konkan summer. That’s when he sought Swades Foundation's support with drip irrigation. Slowly, the farm flourished.</p>
        
        <p class="story-lead image_side">Today, Amar’s farm - once home to rain-fed paddy only - is thriving with mango, cashew, turmeric, avocado, pineapple, and organically grown dragon fruit. His last dragon fruit harvest yielded 200 kgs, making it a source of inspiration for farmers in the region.</p>
      </div>
