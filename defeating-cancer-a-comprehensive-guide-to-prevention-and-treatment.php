        <div class="initiative">
          <h5>At the beginning of 2024, as is the case every year, the gyms were flooded with new members, people took up yoga, decided to watch what they eat etc.
How many of us still continue to follow the above activities today? Hardly any, right?</h5>
          <p>We may not be aware, but there are multiple conditions, gradually increasing globally which are potential silent pandemics in the making. Non-communicable diseases including Diabetes, Hypertension and Cancer are some of these.</p>
          <h5>Statistics and global impact of cancer</h5>
          <p>Deaths from noncommunicable diseases, including cancer, have increased from 57% in 1990 to 74% in 2019 in both men and women (and in women specifically from 58% to 76%) over the past 30 years. By the year 2019, non-communicable diseases were responsible for three out of four deaths worldwide. Today, cardiovascular disease and cancer are the leading causes of premature death among women in more than 130 countries, 33 with cancer ranking first in 82 of these (including Brazil and China).

Cancer ranks in the top three causes of premature mortality among women in almost all countries of the world. In 2020, 9·23 million women worldwide were diagnosed with cancer, and 4·43 million women died of cancer. By 2040, these numbers are projected to increase to 13·3 million new cases and 7·1 million deaths, representing a 44% increase in new cases and a 60% increase in deaths. 1·5 million deaths could be averted through primary prevention or early detection strategies, while a further 800000 deaths could be averted if all women everywhere could access optimal cancer care.

The World Health Assembly Resolution, “Cancer prevention and control in the context of an integrated approach”, was adopted by 194 member states in 2017. It drew attention to the increasing burden and economic impact of cancer, estimated to cost US$1·16 trillion a year (a number expected to grow exponentially), and for which there are scant resources.
The cancer burden continues to grow globally, exerting tremendous physical, emotional and financial strain on individuals, families, communities and health systems.</p>

          <p>Cancer also has a wide range of social consequences. A recent analysis showed that in 2020 alone, there were an estimated 1 million maternal orphans (children left motherless) due to a death from cancer. Most of these children lost their mothers due to breast cancer (25%), cervical cancer (20%), or upper-gastrointestinal cancer (13%), and most maternal deaths occurred in Asia and Africa.</p>
