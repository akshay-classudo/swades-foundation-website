            <h5>Community Empowerment Team (CET): Enabling Exit with Lasting Impact</h5>
            <p>CET is not just a training team. It is Swades Foundation’s core driver for community engagement and empowerment. Aligned with Swades’ 4E strategy and the ultimate goal of a successful Exit, CET builds local capacity by equipping community members with the right knowledge and tools to sustain development independently.
 
Since 2022, CET has conducted over 9,000 sessions, impacting 1 lakh+ individuals across villages in sectors like health, education, livelihoods, and sanitation. At the heart of CET is the Gyan Mitra Cadre — a strong and growing network of 158+ certified local trainers, delivering 40+ practical, contextual modules such as goat rearing, financial literacy, and waste management.
CET is creating a future where knowledge grows within the community, ensuring sustainable change continues from the grassroots, by the grassroots.
</p>
