      <span>Reflection</span>
      <h2>Reforming Pay Structures in the Social Sector Will Benefit Everyone</h2>
      <p></p>
    </div><!--detail-hd-->

    <div class="detail-werap">
      <div class="initiative">
        <h5>For most young professionals, compensation is the first filter when evaluating a job opportunity.</h5>

        <p>When entry-level salaries are low, capable and driven talent often doesn't even consider a career in the NGO sector. At the same time, we expect this sector to tackle some of the country's and the world's most complex challenges such as poverty, water scarcity, education gaps, healthcare, livelihoods, and climate change. This extends to other critical roles as well - such as teachers or certain public service positions.</p>

        <p>We are asking people to take on deeply complex, high-stakes work, while compensating them far below what that responsibility demands.</p>

        <p>What often does not get addressed enough - especially by corporates and those who want to support meaningful change - is that development work cannot run on passion alone. Passion matters, but it cannot pay the bills. This work demands skill, intellectual capacity, persistence, and a highly capable workforce that can navigate community trust, bureaucracy, infrastructure gaps, and policy limitations, all while staying committed for the long term.</p>

        <p>At the same time, the landscape in which nonprofits operate has become far more complex. Increased expectations around compliance and deliverables in recent years have added significant pressure on organisations. This has made it essential to bring in specialists across key functions such as finance, IT and systems, HR, and fundraising. While this does increase organisational costs, it is also critical to building strong institutions and attracting the kind of talent needed to deliver sustained, high-quality impact.</p>
      </div>

      <div class="blog-post">
        <img src="./assets/images/Blogs/reflection4.png" alt="">
      </div>

      <div class="initiative2">
        <h5>Investing in people is investing in impact</h5>

        <p>When salaries are subpar, natural consequences follow - talent moves out (often to CSR roles, consulting firms, and corporate jobs). What remains is a constant cycle of hiring and rehiring, high attrition, and the gradual erosion of institutional knowledge. Continuity suffers and relationships with communities weaken - much like what we see in teaching and some public sectors.</p>

        <p>Given the critical role the social sector plays in helping countries achieve their Sustainable Development Goals, and the fact that the work is often draining mentally, emotionally, and physically, it should command greater value, not less. And yet, we have normalised low pay almost as a marker of authenticity.</p>

        <p>Part of the challenge lies in how funding is structured. Many NGOs operate under tight donor restrictions, where every rupee is accounted for against visible outputs such as programs, assets, and activities. Meanwhile, the essential costs of people, capacity, and systems are squeezed. Organisations are expected to produce detailed reports, documentation, media visibility, and compliance outputs, often without adequate provision for the time and talent these require.</p>

        <p>We speak often about transparency in the sector, and rightly so. But perhaps it is time to also be transparent about this: many NGOs are simply not able to pay their people what they deserve.</p>

        <h5>How do we begin to change this?</h5>

        <ul>
          <li>First, donors must move towards more capacity building or bearing the cost of training of employees, trusting organisations to allocate resources where they are most needed.</li>

          <li>Second, NGOs themselves must consciously prioritise salaries and talent investment within their budgets, even when it is difficult.</li>

          <li>Third, funders need to recognise the simple fact that investing in people is not an overhead, but the very foundation of impact. We can only build a sector that can operate at scale when we value the people who make that possible.</li>
        </ul>

        <h5>I'd love to hear your thoughts on:</h5>

        <ol>
          <li>Are you willing to invest in social sector talent at a level that matches the complexity of the work?</li>
          <li>How can we design budgets that truly reflect the cost of talent?</li>
          <li>How do we ensure that social sector professionals are fairly compensated?</li>
        </ol>

