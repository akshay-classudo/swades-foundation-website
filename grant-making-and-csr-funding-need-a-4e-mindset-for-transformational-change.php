      <span>Reflection</span>
      <h2>Grant Making and CSR Funding Need a "4 E MINDSET” FOR TRANSFORMATIONAL CHANGE</h2>
      <p></p>
    </div><!--detail-hd-->

    <div class="detail-werap">
      <div class="initiative">
        <h5>At Swades, we believe sustainable change cannot be delivered to communities - it must be built with them. That conviction is the foundation of our 4E model: Engage. Enable. Execute. Excel in that order.</h5>

        <p>I believe that CSR and philanthropy too can be better aligned if we adopt this approach. In a complex funding landscape, donor partnerships by default are centred around Execute - beneficiaries reached, resources utilised, milestones ticked, etc. These questions matter, but a partnership measured only by execution will always stay transactional. The deeper opportunity lies in the other three Es.</p>

        <p>I encourage funders and donors today to assess themselves not only on execution, but equally on the other three Es - and rate themselves on a scale of 1 to 10 or high to low.</p>

        <h5>Engage</h5>

        <p>Alignment of purpose is the starting point, but true engagement also requires a deep understanding of how non-profits work on the ground. Not through reports alone, but through field immersion, dialogue, and shared strategy. That is when the relationship between a funder and grantee evolves into one of true partners in change.</p>

        <h5>Enable</h5>

        <p>This begins with understanding and acknowledging capacity gaps, and setting realistic expectations for both partners. It means investing not only in programmes, but in the institution itself. The donors who shaped us most invested in our people, systems, and leadership - not just in deliverables.</p>
      </div>

      <div class="blog-post">
        <img src="./assets/images/Blogs/reflection9.png" alt="">
      </div>

      <div class="initiative2">
        <h5>The 4E Mindset for Transformational Change</h5>

        <p>This is a two-way process. Funders too can evolve through these partnerships. Today, many CSR functions are led by communications, HR, or sustainability teams that may not come from development backgrounds. In such cases, non-profits can play a valuable role in helping corporate partners better understand grassroots realities, community engagement, implementation challenges, and ultimately enable more informed decisions and stronger collective impact.</p>

        <h5>Execute</h5>

        <p>Of course, execution remains the foundation of any meaningful development partnership. Communities deserve programmes that are delivered with rigour, accountability, and consistency. Outcomes matter, along with timelines.</p>

        <h5>Excel</h5>

        <p>The most under-discussed stage. A partnership excels when both sides grow because of it: models become replicable, communities become self-sustaining, and dependence fades. True excellence is not perpetual dependency; it is building the conditions for independence. This requires funders to commit for the longer term and to critically assess programme design through the lens of sustainability.</p>

        <p>The partnerships that shaped Swades most were those where our donor partners moved from asking us, <strong>"What are we funding?"</strong> to <strong>"What are we building together?"</strong> That is the shift philanthropy needs today.</p>

        <p>Funders too should bring in and share the learnings on these three Es - Engage, Enable, and Excellence - with all their NGO partners.</p>

        <p>We at Swades will be happy to share our learnings and jointly build the process and pilot of the 4E strategy for grant making.</p>

        <p>I look forward to those who are ready to innovate and work for sustainable change.</p>

