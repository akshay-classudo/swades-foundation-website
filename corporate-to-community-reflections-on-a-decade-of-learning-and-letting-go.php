      <span>Reflection</span>
      <h2>Corporate to Community: Reflections on a Decade of Learning and Letting Go</h2>
      <p></p>
    </div><!--detail-hd-->

    <div class="detail-werap">
      <div class="initiative">
        <h5>Ten years ago, I made a defining decision of my professional life - to walk away from 27 years in the corporate world to pursue the social sector.</h5>

        <p>For decades, my world (at Mahindra, Godrej, Fullerton and Thomson Reuters) was shaped by clear targets, defined metrics, large teams, structured processes etc. Then, within days of joining Swades Foundation, I found myself in the villages of Raigad.</p>

        <p>Within a few weeks, I realised that my corporate cheat sheet was falling short here. I still remember those early visits. I'd gone in thinking I'd understand the problems and help fix them. What I found instead was that I was doing a lot more listening and learning than talking.</p>

        <p>I was now a student in a whole new classroom and with a very different syllabus.</p>

        <p>Despite the nature of change in the environment, what made that leap a little less daunting was the generosity of our co-founders, Ronnie and Zarina, who gave me the room to find my footing. Apart from the rest of the team and of course the communities who slowly and graciously opened their doors.</p>
      </div>

      <div class="blog-post">
        <img src="./assets/images/Blogs/carporate-to-community.png" alt="carporate-to-community">
      </div>

      <div class="initiative2">
        <h5>Some reflections return time and again:</h5>

        <ul>
          <li>We are blessed as we are able to do some meaningful work for social good.</li>
          <li>Good intent, principled governance and impactful work makes it easy and highly satisfying.</li>
          <li>There is so much that the corporate world can learn from the social sector.</li>
          <li>There is always so much more to do, always.</li>
          <li>Unstructured situations in the social sector offer great opportunities to learn and grow.</li>
        </ul>

        <p>This is the first of 10 blogs I'll be sharing as I reflect on my decade in the sector, and at Swades. It is my humble attempt to make sense of the journey so far and add perspective to what lies ahead.</p>

        <p>I hope it offers some useful insights, but more importantly, I hope it sparks conversations and gives me the opportunity to hear diverse perspectives from my peers and network here. If there is a particular topic which you'd like me to touch upon, please.</p>

