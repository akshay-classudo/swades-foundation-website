            <h5>Village Development Committee (VDC): Driving Change from Within</h5>
            <p>At Swades, sustainable development begins with empowered communities. Our Village Development Committees
              (VDCs) are democratically formed, gender-balanced groups (50% or more women) of local volunteers who lead
              change at the grassroots. Mentored by Swades, VDCs take ownership of village-level planning, execution,
              and monitoring across sectors — from health and education to water and livelihoods. Acting as the voice
              and anchor of their communities, they form the nucleus of all Swades activities — ensuring transparency,
              accountability, and continuity.
