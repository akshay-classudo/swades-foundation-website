      <span>Reflection</span>
      <h2>Social Sector Thrives on Collaboration, Not Competition</h2>
      <p></p>
    </div><!--detail-hd-->

    <div class="detail-werap">
      <div class="initiative">
        <h5>A question I am asked more and more often - especially as Swades expands into new geographies already with the presence of well-meaning organisations is this: "Are you not worried about other NGOs working in the same villages as you?"</h5>

        <p>My answer is always 'no'. In fact, I am encouraged by it.</p>

        <p>This instinct to treat overlap as threat is inherited from the private sector, where market share is finite and a customer gained by a competitor is a customer lost by you. But in the social sector, we are not fighting over customers. We are working alongside communities. And that is a battle no single organisation can win alone. The private sector works with competition, but the social sector thrives on collaboration.</p>

        <p>A recent visit from a potential partner reminded me why that is the case. Walking through our villages together, the new potential partner noticed several NGOs already at work - from plastic waste management to agro-forestry. Quite naturally, they asked why so many NGOs were operating in the same cluster of villages.</p>

        <p>This was my response - when a community is truly mobilised and encouraged to act, its trust extends far beyond a single programme. It becomes a catalyst for many others to build on.</p>
      </div>

      <div class="blog-post">
        <img src="./assets/images/Blogs/reflection3.png" alt="">
      </div>

      <div class="initiative2">
        <h5>Collaboration creates sustainable impact</h5>

        <p>We saw this clearly in our partnership with Green Communities Foundation (GCF), which supports Swades villages with plastic recycling. The organisation trained communities on waste segregation, provided bags for dry waste, but most importantly helped them recognise the value in recycling the waste that they generate. They also established a structured system with defined collection points and regular pick-ups.</p>

        <p>What made this initiative effective was not just the intervention, but the community's readiness to embrace it. The partnership succeeded because both organisations built on each other's strengths. While Swades laid a strong foundation through deep community mobilisation, GCF brought in its expertise in plastic waste management. Together, this translated into cleaner, greener villages - a win-win.</p>

        <p>GCF could seamlessly implement its programme, as villages, having previously engaged with Swades Foundation, were already receptive and proactive. Today, tonnes of plastic waste are channelled to processing units each month, significantly reducing environmental burden. In a powerful example of circular impact, some village schools are now equipped with furniture made from recycled plastic.</p>

        <p>The same logic governs our partnership with Sankara Eye Hospital, Shantilal Shanghvi Eye Institute and SMBT Hospital on healthcare. Swades mobilises communities and builds trust; our partners bring deep domain expertise. The result? Villagers receiving free cataract surgeries not as a one-off camp, but as a reliable service. Over 22,000 have had their sight restored because two organisations did what they do best.</p>

        <p>Perhaps the most underleveraged collaboration is with the government. India's welfare architecture presents a massive resource base, yet the distance between a scheme's existence and a villager's access remains a huge gap. Our Government Convergence team bridges exactly this by helping communities navigate entitlements that were always meant for them.</p>

        <p>True collaboration demands something of every partner: the honesty to acknowledge what we cannot do, the humility to let others lead where they are stronger, and the restraint to not plant our flag in every field.</p>

        <p>What it gives back is far greater. Not an organisation that does everything, but an ecosystem where everything gets done.</p>

        <h5>What I'd like to know from you is:</h5>

        <ul>
          <li>Would you be interested in partnering with us? If so, which specific area of intervention in our rural geographies would you like to support?</li>
          <li>What have been your struggles with collaboration?</li>
          <li>Do you believe that the corporate sector can draw learnings from the social sector?</li>
        </ul>

